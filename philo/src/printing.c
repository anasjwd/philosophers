#include "philo.h"

void	ft_putchar_fd(char c, int fd)
{
	write(fd, &c, 1);
}

void	ft_putstr_fd(char *str, int fd)
{
	int	idx;

	idx = 0;
	while (str[idx])
		ft_putchar_fd(str[idx++], fd);
}
